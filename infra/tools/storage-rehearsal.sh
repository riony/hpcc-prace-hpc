#!/usr/bin/env bash
# Storage rehearsal harness (D39 storage step), run from the control workstation. Two throwaway VMs
# on the login node's rehearsal host (roles/rehearsal_host) stand in for the login node and a
# client, so the storage roles (login_storage, storage_policy, nfs_home) and the /home cutover run
# against disposable disks BEFORE production is touched.
#
#   infra/tools/storage-rehearsal.sh up [--hold-on-failure]
#   infra/tools/storage-rehearsal.sh status
#   infra/tools/storage-rehearsal.sh wait sr-login|sr-client [--timeout SECONDS]
#   infra/tools/storage-rehearsal.sh down
#
# With the VMs up (a storage playbook imports playbooks/storage-rehearsal-guard.yml first):
#   infra/tools/run-ansible.sh -i inventories/storage-rehearsal playbooks/<playbook>.yml
#   ssh -F ~/.cache/prace-storage-rehearsal/ssh_config sr-login           (root; admin@sr-login as admin)
# 'wait <vm>' blocks until the VM answers ssh again with its pinned host key (after a reboot in the
# cutover) and reports the systemd state; exit 0 only when the system is "running".
#
# The VMs (the Rocky 9.8 cloud image pinned by sha256, the same one tools/restore-rehearsal.sh uses):
#   sr-login   4 vCPU / 4096 MiB; 20G OS overlay (disk serial prace-sr-login-os) and a blank 24G disk
#              (serial prace-sr-data) holding PV + VG sr_vg and no LV, like production hpe_vg before
#              the storage step. /home stays a plain directory on the root filesystem, as on
#              production today. Private link address 10.90.10.1/25 (the login node's admin_ip).
#   sr-client  2 vCPU / 2048 MiB; 20G OS overlay (serial prace-sr-client-os); link 10.90.10.21/25.
#   Both: hostname = VM name; root and 'admin' (uid/gid 1000, wheel, /home/admin, /bin/bash, as the
#   kickstart creates it; password locked) accept one throwaway key; dnf sees only the repository
#   disk (label prace-sr-repo, read-only, mounted at /mnt/prace-sr-repo): /srv/fleet-repo plus the
#   storage packages downloaded with their dependencies on the login node, every one checked there
#   against the Rocky 9 key, and gpgcheck=1 inside, as the restore rehearsal installs.
#
# Isolation, as the restore rehearsal: the VMs run as the rehearsal user behind the memory guard,
# with QEMU user networking and restrict=on; the only way in is an ssh forward on the login node's
# 127.0.0.1 (2242 sr-login, 2252 sr-client), reached through the login node with the throwaway key.
# The two VMs share a private UDP link (-netdev dgram, 127.0.0.1:47121 <-> 47122) that reaches
# nothing else. 'up' proves that neither VM reaches the QEMU host, the login node, the fleet, a BMC,
# the K3s service network or the internet, and fails otherwise. A VM's host key is trusted only when
# ssh sees the ED25519 key its serial console printed.
#
# 'up' refuses while anything of an earlier run exists; on failure it deletes the VMs, unless
# --hold-on-failure was given AND isolation had been proven. 'down' stops the VMs, deletes their disks
# and state directory and the local key directory, and proves the ports are free. The key, known_hosts
# and ssh config live in ~/.cache/prace-storage-rehearsal (0700), regenerated by every 'up'.
# This tool never touches the restore rehearsal (/var/lib/prace-rehearsal/restore, ports 2231/2232,
# 47101/47102), production services, K3s, NFS exports, /home or LVM on the login node, and never
# takes or releases the cluster lease.
set -euo pipefail

LOGIN=192.0.2.205
RUSER=prace-rehearsal
SDIR=/var/lib/prace-rehearsal/storage
CACHE=/var/lib/prace-rehearsal/images
# The same pinned base image as tools/restore-rehearsal.sh (tools/test-storage-rehearsal.py checks it).
IMG=Rocky-9-GenericCloud-Base-9.8-20260525.0.x86_64.qcow2
IMG_URL=https://dl.rockylinux.org/pub/rocky/9.8/images/x86_64/$IMG
IMG_SHA=92c206cc6f790c61583247eefe87890f8828420662c17cacf247cec78ab4eec8
VMS="sr-login sr-client"
declare -A PORT=([sr-login]=2242 [sr-client]=2252)            # ssh forwards on the login node's 127.0.0.1
declare -A CPUS=([sr-login]=4 [sr-client]=2)
declare -A MIB=([sr-login]=4096 [sr-client]=2048)
declare -A OS_SERIAL=([sr-login]=prace-sr-login-os [sr-client]=prace-sr-client-os)
declare -A NAT_MAC=([sr-login]=52:54:00:4e:53:21 [sr-client]=52:54:00:4e:53:31)
declare -A LINK_MAC=([sr-login]=52:54:00:4e:53:22 [sr-client]=52:54:00:4e:53:32)
declare -A LINK_IP=([sr-login]=10.90.10.1 [sr-client]=10.90.10.21)
declare -A LINK_PORT=([sr-login]=47121 [sr-client]=47122)     # UDP on the login node's 127.0.0.1 (the link)
OS_DISK=20G DATA_DISK=24G DATA_SERIAL=prace-sr-data VG=sr_vg
REPO_LABEL=prace-sr-repo REPO_MNT=/mnt/prace-sr-repo
# What the storage roles install, downloaded with every dependency (resolved as for an empty system).
STORAGE_PACKAGES="nfs-utils quota quota-nls quota-rpc xfsprogs acl rsync lvm2 policycoreutils-python-utils python3-libsemanage e2fsprogs"
CHECK_PACKAGES="rsync quota-rpc nfs-utils xfsprogs"
KEYDIR=$HOME/.cache/prace-storage-rehearsal
TRUST_TRIES=60 TRUST_SLEEP=5           # console fingerprint: up to 300 s
UP_ATTEMPTS=30 UP_SLEEP=5              # first ssh contact

# ---------------------------------------------------------------------------------------------
STAGE=start CREATED=0 ISOLATED=0 HOLD=0 MUX=""
fail() { echo "   FAIL: $*"; exit 1; }
q() { printf %q "$1"; }     # a value with spaces or newlines crosses the ssh command line quoted

# One multiplexed connection to the login node per invocation, in a private directory (its sshd
# penalises bursts of new connections; never a socket shared with another tool).
mux_open() { MUX=$(mktemp -d "${XDG_RUNTIME_DIR:-/tmp}/prace-sr.XXXXXX"); }
mux_close() {
  [ -n "$MUX" ] && [ -d "$MUX" ] || return 0
  local s
  # the VM connections ride on the login node's: close them first (a stale socket is no error)
  for s in "$MUX"/sr-* "$MUX"/login; do
    if [ -S "$s" ]; then ssh -o ControlPath="$s" -O exit x >/dev/null 2>&1 || true; fi
  done
  rm -rf "$MUX"; MUX=""
}
L() { ssh -o BatchMode=yes -o ConnectTimeout=10 -o ControlMaster=auto -o ControlPath="$MUX/login" -o ControlPersist=900 "root@$LOGIN" "$@"; }
V() {   # V <vm> command...: root (VUSER=admin: admin) in a VM, through the login node's connection
  local vm=$1 user=${VUSER:-root}; shift
  ssh -o BatchMode=yes -o ConnectTimeout=20 -o ControlMaster=auto -o ControlPath="$MUX/$vm-$user" -o ControlPersist=900 \
      -o ProxyCommand="ssh -o BatchMode=yes -o ControlPath=$MUX/login -W %h:%p root@$LOGIN" \
      -o HostKeyAlgorithms=ssh-ed25519 -o UserKnownHostsFile="$KEYDIR/known_hosts" -o StrictHostKeyChecking="${SHK:-yes}" \
      -o IdentitiesOnly=yes -i "$KEYDIR/id" -p "${PORT[$vm]}" "$user@127.0.0.1" "$@"
}

# ---------------------------------------------------------------------------------------------
# Throwaway key, empty known_hosts and the ssh config (for people and for Ansible's jump host).
make_keydir() {
  if [ -S "$KEYDIR/jump" ]; then ssh -o ControlPath="$KEYDIR/jump" -O exit "$LOGIN" >/dev/null 2>&1 || true; fi
  rm -rf "$KEYDIR"; mkdir -p "$(dirname "$KEYDIR")"; mkdir -m 700 "$KEYDIR"
  ssh-keygen -q -t ed25519 -N '' -C prace-storage-rehearsal -f "$KEYDIR/id"
  : > "$KEYDIR/known_hosts"
  cat > "$KEYDIR/ssh_config" <<EOF
# Written by infra/tools/storage-rehearsal.sh up; removed by 'down'. For people:
#   ssh -F $KEYDIR/ssh_config sr-login              (root)
#   ssh -F $KEYDIR/ssh_config admin@sr-client
# inventories/storage-rehearsal passes this file with -F for the jump host's settings only.
Host sr-login
  HostName 127.0.0.1
  Port ${PORT[sr-login]}
Host sr-client
  HostName 127.0.0.1
  Port ${PORT[sr-client]}
Host sr-login sr-client
  User root
  ProxyJump root@$LOGIN
  IdentityFile $KEYDIR/id
  IdentitiesOnly yes
  UserKnownHostsFile $KEYDIR/known_hosts
  StrictHostKeyChecking yes
  HostKeyAlgorithms ssh-ed25519
  BatchMode yes
# The jump: the workstation's normal known_hosts, strictly; one multiplexed connection shared by
# the sessions that use this file (the login node's sshd penalises bursts of new connections).
Host $LOGIN
  User root
  UserKnownHostsFile ~/.ssh/known_hosts
  StrictHostKeyChecking yes
  BatchMode yes
  ControlMaster auto
  ControlPath $KEYDIR/jump
  ControlPersist 300
EOF
  chmod 600 "$KEYDIR/ssh_config" "$KEYDIR/known_hosts"
}

# cloud-init NoCloud seed: hostname, root + admin keys, the link address (matched by MAC), the
# repository disk as the only dnf source and, on sr-login, PV + VG on the data disk.
repo_file() {
  cat <<EOF
# Storage rehearsal (tools/storage-rehearsal.sh): the read-only repository disk is the only source.
[prace-sr-fleet]
name=PRACE fleet repository (storage rehearsal repository disk)
baseurl=file://$REPO_MNT/fleet-repo
enabled=1
gpgcheck=1
gpgkey=file://$REPO_MNT/fleet-repo/keys/RPM-GPG-KEY-Rocky-9 file://$REPO_MNT/fleet-repo/keys/RPM-GPG-KEY-EPEL-9 file://$REPO_MNT/fleet-repo/keys/RPM-GPG-KEY-OpenHPC-3
skip_if_unavailable=0

[prace-sr-storage]
name=Storage packages with their dependencies (storage rehearsal repository disk)
baseurl=file://$REPO_MNT/storage-repo
enabled=1
gpgcheck=1
gpgkey=file://$REPO_MNT/fleet-repo/keys/RPM-GPG-KEY-Rocky-9
skip_if_unavailable=0
EOF
}
firstboot_script() {   # firstboot_script <vm>
  cat <<EOF
#!/bin/bash
# Storage rehearsal first boot (tools/storage-rehearsal.sh, via cloud-init runcmd).
set -euo pipefail
# No internet here: every repository but the repository disk's is disabled.
for f in /etc/yum.repos.d/*.repo; do
  [ "\$f" = /etc/yum.repos.d/prace-sr.repo ] || sed -i -E 's/^enabled[[:space:]]*=.*/enabled=0/' "\$f"
done
mountpoint -q $REPO_MNT
EOF
  if [ "$1" = sr-login ]; then
    cat <<EOF
# The volume group pre-exists, like production hpe_vg: PV + VG on the data disk, no LV.
rpm -q lvm2 >/dev/null || dnf -y -q install lvm2
pvcreate -q /dev/disk/by-id/virtio-$DATA_SERIAL
vgcreate -q $VG /dev/disk/by-id/virtio-$DATA_SERIAL
EOF
  fi
}
make_seed() {   # make_seed <vm>: $KEYDIR/seed-<vm>.iso
  local vm=$1 d=$KEYDIR/seed-$1 key
  key=$(cat "$KEYDIR/id.pub")
  mkdir -p "$d"
  printf 'instance-id: prace-sr-%s-%s\nlocal-hostname: %s\n' "$vm" "$(date +%s)" "$vm" > "$d/meta-data"
  cat > "$d/network-config" <<EOF
version: 2
ethernets:
  nat0:
    match:
      macaddress: "${NAT_MAC[$vm]}"
    dhcp4: true
  link0:
    match:
      macaddress: "${LINK_MAC[$vm]}"
    dhcp4: false
    addresses: [${LINK_IP[$vm]}/25]
EOF
  {
    cat <<EOF
#cloud-config
hostname: $vm
preserve_hostname: false
timezone: Asia/Singapore
disable_root: false
ssh_pwauth: false
ssh_authorized_keys:
  - $key
# The kickstart's admin user (kickstart/build-ks.sh: user --name=admin --groups=wheel; its key in
# /home/admin/.ssh/authorized_keys). No password here: it is locked.
users:
  - name: admin
    uid: 1000
    groups: [wheel]
    homedir: /home/admin
    shell: /bin/bash
    lock_passwd: true
    ssh_authorized_keys:
      - $key
mounts:
  - [LABEL=$REPO_LABEL, $REPO_MNT, ext4, "ro,nofail,x-systemd.device-timeout=30s", "0", "0"]
write_files:
  - path: /etc/yum.repos.d/prace-sr.repo
    permissions: "0644"
    content: |
EOF
    repo_file | sed 's/^/      /'
    cat <<EOF
  - path: /usr/local/sbin/prace-sr-firstboot
    permissions: "0700"
    content: |
EOF
    firstboot_script "$vm" | sed 's/^/      /'
    cat <<EOF
runcmd:
  - [/usr/local/sbin/prace-sr-firstboot]
EOF
  } > "$d/user-data"
  # parse before use: a seed cloud-init cannot read fails silently inside the VM
  python3 - "$d/user-data" "$d/network-config" "$d/meta-data" <<'PY' || fail "seed for $vm does not parse"
import sys, yaml
u = yaml.safe_load(open(sys.argv[1]))
assert open(sys.argv[1]).readline().strip() == "#cloud-config"
assert u["users"][0]["name"] == "admin" and u["runcmd"] and u["write_files"][1]["content"].startswith("#!/bin/bash")
for f in sys.argv[2:]:
    yaml.safe_load(open(f))
PY
  genisoimage -quiet -output "$KEYDIR/seed-$vm.iso" -volid cidata -joliet -rock "$d/user-data" "$d/meta-data" "$d/network-config"
}

# ---------------------------------------------------------------------------------------------
stage_preflight() {
  STAGE=preflight
  echo "== $(date +%T) preflight on the login node (nothing of an earlier run, ports free, memory guard)"
  local total=$(( ${MIB[sr-login]} + ${MIB[sr-client]} ))
  L SDIR="$SDIR" RUSER="$RUSER" TOTAL="$total" TCP="$(q "${PORT[sr-login]} ${PORT[sr-client]}")" \
    UDP="$(q "${LINK_PORT[sr-login]} ${LINK_PORT[sr-client]}")" bash -s <<'REMOTE'
set -euo pipefail
[ "$SDIR" = /var/lib/prace-rehearsal/storage ] || { echo "refusing: unexpected state directory $SDIR"; exit 3; }
id "$RUSER" >/dev/null && [ -x /usr/local/sbin/prace-rehearsal-memguard ] && [ -x /usr/libexec/qemu-kvm ] \
  || { echo "refusing: rehearsal host not prepared (roles/rehearsal_host)"; exit 3; }
if pgrep -u "$RUSER" -f -- '-name prace-sr-(login|client) ' >/dev/null; then echo "refusing: a storage rehearsal VM is running (run down)"; exit 3; fi
[ ! -e "$SDIR" ] || { echo "refusing: $SDIR exists (run down)"; exit 3; }
for p in $TCP; do [ -z "$(ss -Hltn "sport = :$p")" ] || { echo "refusing: tcp port $p is in use on the login node"; exit 3; }; done
for p in $UDP; do [ -z "$(ss -Hlun "sport = :$p")" ] || { echo "refusing: udp port $p is in use on the login node"; exit 3; }; done
/usr/local/sbin/prace-rehearsal-memguard "$TOTAL" | sed 's/^/   memory guard: /'
# created here, in the same check: from now on this run owns it
mkdir -m 0700 "$SDIR"; chown "$RUSER:$RUSER" "$SDIR"
echo "   $SDIR created (nothing of an earlier run; tcp $TCP and udp $UDP free)"
REMOTE
  CREATED=1
}

stage_prepare() {
  STAGE=prepare
  echo "== $(date +%T) prepare: throwaway key, seeds, disks, repository disk"
  make_keydir
  local vm
  for vm in $VMS; do make_seed "$vm"; done
  L "rm -rf /root/prace-sr-upload && mkdir -m 700 /root/prace-sr-upload"
  scp -q -o ControlPath="$MUX/login" "$KEYDIR/seed-sr-login.iso" "$KEYDIR/seed-sr-client.iso" "root@$LOGIN:/root/prace-sr-upload/"
  L SDIR="$SDIR" CACHE="$CACHE" RUSER="$RUSER" IMG="$IMG" IMG_URL="$IMG_URL" IMG_SHA="$IMG_SHA" VMS="$(q "$VMS")" \
    OS_DISK="$OS_DISK" DATA_DISK="$DATA_DISK" REPO_LABEL="$REPO_LABEL" STORAGE_PACKAGES="$(q "$STORAGE_PACKAGES")" bash -s <<'REMOTE'
set -euo pipefail
umask 077
st=$(mktemp -d /root/prace-sr-stage.XXXXXX); trap 'rm -rf "$st" /root/prace-sr-upload' EXIT

# The pinned base image, cached for every rehearsal (downloaded only when missing).
install -d -m 0750 -o "$RUSER" -g "$RUSER" "$CACHE"
if [ ! -f "$CACHE/$IMG" ]; then
  curl -fsSL -o "$CACHE/$IMG.part.$$" "$IMG_URL"; mv "$CACHE/$IMG.part.$$" "$CACHE/$IMG"
  chown "$RUSER:" "$CACHE/$IMG"; chmod 0440 "$CACHE/$IMG"
fi
got=$(sha256sum "$CACHE/$IMG" | cut -d' ' -f1)
[ "$got" = "$IMG_SHA" ] || { echo "refusing: base image sha256 $got != pinned $IMG_SHA"; exit 4; }
echo "   base image $IMG (sha256 matches the pinned value)"
for vm in $VMS; do
  runuser -u "$RUSER" -- qemu-img create -q -f qcow2 -F qcow2 -b "$CACHE/$IMG" "$SDIR/$vm-os.qcow2" "$OS_DISK"
  install -m 0400 -o "$RUSER" -g "$RUSER" "/root/prace-sr-upload/seed-$vm.iso" "$SDIR/seed-$vm.iso"
done
runuser -u "$RUSER" -- qemu-img create -q -f qcow2 "$SDIR/sr-login-data.qcow2" "$DATA_DISK"
echo "   OS overlays ($OS_DISK) for $VMS, blank $DATA_DISK data disk for sr-login, seeds"

# The repository disk: the fleet repository plus the storage packages with every dependency,
# resolved as for an empty system (--alldeps: the VMs' installed set is not the login node's).
# Downloaded into a throwaway directory only; nothing is installed here, nothing is mounted.
mkdir -p "$st/disk/fleet-repo" "$st/disk/storage-repo" "$st/dl" "$st/keydb"
cp -a --reflink=auto /srv/fleet-repo/packages /srv/fleet-repo/repodata /srv/fleet-repo/keys "$st/disk/fleet-repo/"
dnf -q -y --disablerepo='*' --enablerepo=baseos --enablerepo=appstream \
  download --resolve --alldeps --downloaddir "$st/dl" $STORAGE_PACKAGES >/dev/null
n=$(find "$st/dl" -name '*.rpm' | wc -l)
[ "$n" -gt 0 ] || { echo "refusing: nothing downloaded"; exit 4; }
names=$(rpm -qp --nosignature --qf '%{NAME}\n' "$st/dl"/*.rpm 2>/dev/null | sort -u)
for p in $STORAGE_PACKAGES; do grep -qx "$p" <<<"$names" || { echo "refusing: $p is not in the download"; exit 4; }; done
# Every package must carry a valid Rocky 9 signature: checked against that key alone (a scratch
# key database that the import creates; the login node's own rpm database is not touched).
rpmkeys --dbpath "$st/keydb" --import /srv/fleet-repo/keys/RPM-GPG-KEY-Rocky-9
bad=$(rpmkeys --dbpath "$st/keydb" --checksig "$st/dl"/*.rpm 2>&1 | grep -v ': digests signatures OK$' || true)
[ -z "$bad" ] || { echo "refusing: not signed with the Rocky 9 key:"; echo "$bad" | head -20; exit 4; }
mv "$st/dl"/*.rpm "$st/disk/storage-repo/"
createrepo_c -q "$st/disk/storage-repo"
size=$(( $(du -sm "$st/disk" | cut -f1) * 12 / 10 + 512 ))
mkfs.ext4 -q -F -L "$REPO_LABEL" -d "$st/disk" "$SDIR/repo.img" "${size}M" >/dev/null
chown "$RUSER:" "$SDIR/repo.img"; chmod 0400 "$SDIR/repo.img"
echo "   repository disk ${size} MiB: fleet repository + $n storage packages ($(wc -w <<<"$STORAGE_PACKAGES") named, the rest dependencies; all Rocky 9 signed)"
REMOTE
}

stage_boot() {
  STAGE=boot
  echo "== $(date +%T) boot (memory guard first); private link 127.0.0.1:${LINK_PORT[sr-login]} <-> ${LINK_PORT[sr-client]}"
  local vm spec=""
  for vm in $VMS; do
    spec+="$vm ${CPUS[$vm]} ${MIB[$vm]} ${PORT[$vm]} ${OS_SERIAL[$vm]} ${NAT_MAC[$vm]} ${LINK_MAC[$vm]} ${LINK_PORT[$vm]}"$'\n'
  done
  L SDIR="$SDIR" RUSER="$RUSER" TOTAL="$(( ${MIB[sr-login]} + ${MIB[sr-client]} ))" SPEC="$(q "$spec")" \
    DATA_SERIAL="$DATA_SERIAL" REPO_LABEL="$REPO_LABEL" bash -s <<'REMOTE'
set -euo pipefail
/usr/local/sbin/prace-rehearsal-memguard "$TOTAL" | sed 's/^/   memory guard: /'
peer_port() { awk -v v="$1" '$1 != v && NF {print $8}' <<<"$SPEC"; }
while read -r vm cpus mib port serial nmac lmac lport; do
  [ -n "$vm" ] || continue
  data=()
  [ "$vm" = sr-login ] && data=(-drive "file=$SDIR/sr-login-data.qcow2,if=none,id=data,format=qcow2"
                                -device "virtio-blk-pci,drive=data,serial=$DATA_SERIAL")
  runuser -u "$RUSER" -- /usr/libexec/qemu-kvm -name "prace-$vm" -machine q35,accel=kvm -cpu host \
    -smp "$cpus" -m "$mib" -nodefaults -display none \
    -drive "file=$SDIR/$vm-os.qcow2,if=none,id=os,format=qcow2" -device "virtio-blk-pci,drive=os,serial=$serial,bootindex=0" \
    "${data[@]}" \
    -drive "file=$SDIR/repo.img,if=none,id=repo,format=raw,readonly=on" -device "virtio-blk-pci,drive=repo,serial=$REPO_LABEL" \
    -drive "file=$SDIR/seed-$vm.iso,if=none,id=seed,format=raw,readonly=on" -device virtio-blk-pci,drive=seed \
    -netdev "user,id=n0,restrict=on,hostfwd=tcp:127.0.0.1:$port-:22" -device "virtio-net-pci,netdev=n0,mac=$nmac" \
    -netdev "dgram,id=link,local.type=inet,local.host=127.0.0.1,local.port=$lport,remote.type=inet,remote.host=127.0.0.1,remote.port=$(peer_port "$vm")" \
    -device "virtio-net-pci,netdev=link,mac=$lmac" \
    -serial "file:$SDIR/console-$vm.log" -daemonize -pidfile "$SDIR/$vm.pid"
  echo "   $vm: QEMU $(cat "$SDIR/$vm.pid") started ($cpus vCPU, $mib MiB, ssh forward 127.0.0.1:$port)"
done <<<"$SPEC"
REMOTE
  for vm in $VMS; do trust_hostkey "$vm"; done
}

# Trust a VM only when the ED25519 key ssh sees equals the one its console printed.
trust_hostkey() {   # trust_hostkey <vm>
  local vm=$1 console=$SDIR/console-$1.log fp="" ok="" seen
  for _ in $(seq "$TRUST_TRIES"); do
    fp=$(L "tr -d '\r' < $console 2>/dev/null" | sed -n '/BEGIN SSH HOST KEY FINGERPRINTS/,/END SSH HOST KEY FINGERPRINTS/p' \
         | grep -oE 'SHA256:[A-Za-z0-9+/]{43}[^(]*\(ED25519\)' | grep -oE 'SHA256:[A-Za-z0-9+/]{43}' | sort -u || true)
    [ -n "$fp" ] && break; sleep "$TRUST_SLEEP"
  done
  [ -n "$fp" ] || fail "no host key on the $vm console after $((TRUST_TRIES * TRUST_SLEEP)) s"
  # first contact records the key (ssh keeps the first -o value it sees, hence SHK), then compare
  for _ in $(seq "$UP_ATTEMPTS"); do SHK=accept-new V "$vm" true 2>/dev/null && { ok=1; break; }; sleep "$UP_SLEEP"; done
  [ -n "$ok" ] || fail "ssh to $vm failed"
  seen=$(ssh-keygen -l -F "[127.0.0.1]:${PORT[$vm]}" -f "$KEYDIR/known_hosts" | grep -oE 'SHA256:[A-Za-z0-9+/]{43}' | sort -u || true)
  [ "$seen" = "$fp" ] || fail "HOST KEY MISMATCH on $vm: ssh saw ${seen:-nothing}, console printed $fp"
  echo "   $vm: ssh host key = console host key ($fp)"
}

stage_cloudinit() {
  STAGE=cloud-init
  local vm st
  for vm in $VMS; do
    st=$(V "$vm" "timeout 900 cloud-init status --wait >/dev/null 2>&1; cloud-init status | sed -n 's/^status: //p'") || fail "cloud-init status on $vm could not be read"
    if [ "$st" != done ]; then
      V "$vm" 'cloud-init status --long; tail -n 20 /var/log/cloud-init-output.log' 2>&1 | sed 's/^/   /' || true
      fail "cloud-init on $vm ended '${st:-unknown}', not 'done'"
    fi
    echo "   $vm: cloud-init done"
  done
}

# Isolation is asserted, not printed: every probe must answer BLOCKED. A connection, or a probe
# that cannot run, fails the run (and the VMs are deleted: isolation was not proven). Probed with
# the private link up; the peer's link address is the only thing a VM may reach.
ISOLATION_TARGETS="10.0.2.2:22 192.0.2.205:22 10.90.10.13:22 198.18.0.126:443 10.43.0.1:443 1.1.1.1:443"
isolation_probe() {   # isolation_probe <vm>
  local vm=$1 t out bad=""
  for t in $ISOLATION_TARGETS; do
    out=$(V "$vm" "timeout 5 bash -c '</dev/tcp/${t%:*}/${t#*:}' 2>/dev/null && echo REACHABLE || echo BLOCKED") \
      || fail "isolation probe from $vm to $t could not run"
    [ "$out" = BLOCKED ] || bad="$bad $t(${out:-no answer})"
  done
  [ -z "$bad" ] || fail "isolation: reachable or unknown from inside $vm:$bad"
  echo "   isolation ($vm): all $(wc -w <<<"$ISOLATION_TARGETS") probes blocked (QEMU host, login node, fleet, BMC, K3s services, internet)"
}
stage_isolation() {
  STAGE=isolation
  local vm
  for vm in $VMS; do isolation_probe "$vm"; done
  ISOLATED=1
}

# What cloud-init must have produced, read in the VM and compared here (every line must hold).
FACTS_SCRIPT='
set -uo pipefail
echo "hostname $(hostname)"
echo "admin $(id admin 2>&1)"
echo "passwd $(getent passwd admin | cut -d: -f3,4,6,7)"
echo "admin-keys $(stat -c "%U %a" /home/admin/.ssh/authorized_keys 2>&1)"
IF=$(ip -o link | awk -v m="$LINK_MAC" '"'"'tolower($0) ~ m {sub(":", "", $2); print $2}'"'"')
echo "link ${IF:-none} $(ip -o -4 addr show dev "${IF:-lo}" 2>/dev/null | awk '"'"'{print $4}'"'"' | paste -sd,)"
root=$(findmnt -no SOURCE /)
echo "os-disk $(lsblk -ndo SERIAL "/dev/$(lsblk -ndo PKNAME "$root")")"
[ "$(findmnt -no SOURCE --target /home)" = "$root" ] && echo "home root-fs" || echo "home $(findmnt -no SOURCE --target /home)"
echo "repo-mount $(findmnt -no OPTIONS "$REPO_MNT" | tr , "\n" | grep -x ro || echo missing)"
echo "repos $(dnf -q repolist --enabled 2>&1 | awk '"'"'NR > 1 {print $1}'"'"' | sort | paste -sd" ")"
if [ "$(hostname)" = sr-login ]; then
  echo "vg $(vgs --noheadings -o vg_name,pv_count,lv_count "$VG" 2>&1 | xargs)"
  pv=$(pvs --noheadings -o pv_name --select vg_name="$VG" 2>/dev/null | xargs)
  echo "vg-disk $(lsblk -ndo SERIAL "${pv:-/nonexistent}" 2>&1)"
fi
'
check_facts() {   # check_facts <vm> <facts>: fail unless every expected line is present
  local vm=$1 facts=$2 want bad=""
  local -a expect=(
    "hostname $vm"
    "admin uid=1000(admin) gid=1000(admin) groups=1000(admin),10(wheel)"
    "passwd 1000:1000:/home/admin:/bin/bash"
    "admin-keys admin 600"
    "os-disk ${OS_SERIAL[$vm]}"
    "home root-fs"
    "repo-mount ro"
    "repos prace-sr-fleet prace-sr-storage"
  )
  [ "$vm" = sr-login ] && expect+=("vg $VG 1 0" "vg-disk $DATA_SERIAL")
  for want in "${expect[@]}"; do
    grep -qxF -- "$want" <<<"$facts" || bad="$bad"$'\n'"     expected '$want', got '$(grep -m1 "^${want%% *} " <<<"$facts" || echo nothing)'"
  done
  grep -qxE "link [a-z0-9]+ ${LINK_IP[$vm]//./\\.}/25" <<<"$facts" \
    || bad="$bad"$'\n'"     expected the link address ${LINK_IP[$vm]}/25, got '$(grep -m1 '^link ' <<<"$facts" || echo nothing)'"
  [ -z "$bad" ] || fail "$vm is not as cloud-init should have left it:$bad"
}
stage_verify() {
  STAGE=verify
  echo "== $(date +%T) verify: identities, disks, volume group, link, repository"
  local vm facts
  for vm in $VMS; do
    facts=$(V "$vm" LINK_MAC="${LINK_MAC[$vm]}" REPO_MNT="$REPO_MNT" VG="$VG" bash -s <<<"$FACTS_SCRIPT") || fail "facts from $vm could not be read"
    check_facts "$vm" "$facts"
    [ "$(VUSER=admin V "$vm" 'echo "$(id -un) $HOME"')" = "admin /home/admin" ] || fail "ssh as admin into $vm failed"
    echo "   $vm: root and admin (1000:1000, wheel) log in with the throwaway key; link $(grep '^link ' <<<"$facts" | cut -d' ' -f2-); OS disk ${OS_SERIAL[$vm]}; /home on the root filesystem; dnf sees only the repository disk"
  done
  echo "   sr-login: VG $VG on the disk with serial $DATA_SERIAL, no LV"
  [ "$(V sr-login "ping -c 3 -W 2 ${LINK_IP[sr-client]} >/dev/null && echo UP")" = UP ] || fail "sr-login cannot reach sr-client over the link"
  [ "$(V sr-client "ping -c 3 -W 2 ${LINK_IP[sr-login]} >/dev/null && echo UP")" = UP ] || fail "sr-client cannot reach sr-login over the link"
  echo "   private link up both ways (${LINK_IP[sr-login]} <-> ${LINK_IP[sr-client]})"
}

# dnf resolves the storage packages from the repository disk alone (its two repositories are the
# only enabled ones, checked above): the required command, then the whole storage package set.
stage_packages() {
  STAGE=packages
  echo "== $(date +%T) packages: dnf resolves from the repository disk only"
  local vm out
  for vm in $VMS; do
    out=$(V "$vm" "dnf -y install --downloadonly $CHECK_PACKAGES 2>&1") || { sed 's/^/   /' <<<"$out" | tail -20; fail "dnf on $vm: $CHECK_PACKAGES do not resolve"; }
    echo "   $vm: 'dnf -y install --downloadonly $CHECK_PACKAGES' ok ($(grep -oE '^(Install|Upgrade) +[0-9]+ Packages?' <<<"$out" | tr -s ' ' | paste -sd, || true)$(grep -q '^Nothing to do' <<<"$out" && echo 'nothing to do'))"
    out=$(V "$vm" "dnf -y install --downloadonly $STORAGE_PACKAGES 2>&1") || { sed 's/^/   /' <<<"$out" | tail -20; fail "dnf on $vm: the storage package set does not resolve"; }
    echo "   $vm: the whole storage package set resolves ($(grep -oE '^(Install|Upgrade) +[0-9]+ Packages?' <<<"$out" | tr -s ' ' | paste -sd, || true))"
  done
}

# On any failure after this run created its state: delete the VMs unless a diagnostic hold was asked
# for AND isolation had been proven.
on_exit_up() {
  local rc=$?
  if [ "$rc" != 0 ]; then
    echo "RESULT: FAIL (stage $STAGE, exit $rc)"
    if [ "$CREATED" = 1 ]; then
      local vm
      for vm in $VMS; do
        echo "   last console lines of $vm:"
        L "timeout 30 tail -n 15 $SDIR/console-$vm.log 2>/dev/null | tr -d '\r'" 2>/dev/null | sed 's/^/     /' || true
      done
      if [ "$HOLD" = 1 ] && [ "$ISOLATED" = 1 ]; then
        echo "   VMs kept for diagnosis (isolation was proven); delete them with: $0 down"
      else
        do_down || echo "   DOWN FAILED: run '$0 down' and check $SDIR on the login node"
      fi
    fi
  fi
  mux_close
  return "$rc"
}

cmd_up() {
  trap on_exit_up EXIT
  stage_preflight
  stage_prepare
  stage_boot
  stage_cloudinit
  stage_isolation
  stage_verify
  stage_packages
  STAGE=done
  echo "RESULT: UP ($(date +%T)). Key, pinned host keys and ssh config in $KEYDIR"
  echo "   ssh -F $KEYDIR/ssh_config sr-login        (admin@sr-login, sr-client, admin@sr-client)"
  echo "   infra/tools/run-ansible.sh -i inventories/storage-rehearsal <playbook importing storage-rehearsal-guard.yml>"
  echo "   delete everything with: $0 down"
}

# ---------------------------------------------------------------------------------------------
do_down() {
  echo "== $(date +%T) down: stop the VMs, delete their disks and state, remove the throwaway key"
  L SDIR="$SDIR" RUSER="$RUSER" TCP="$(q "${PORT[sr-login]} ${PORT[sr-client]}")" UDP="$(q "${LINK_PORT[sr-login]} ${LINK_PORT[sr-client]}")" bash -s <<'REMOTE' || return 1
set -u
[ "$SDIR" = /var/lib/prace-rehearsal/storage ] || { echo "refusing: unexpected state directory $SDIR"; exit 3; }
pids=$(cat "$SDIR"/sr-login.pid "$SDIR"/sr-client.pid 2>/dev/null; pgrep -u "$RUSER" -f -- '-name prace-sr-(login|client) ')
for pid in $(sort -u <<<"$pids"); do
  # only this harness's VMs: owned by the rehearsal user and named prace-sr-login / prace-sr-client
  [ "$(ps -o user= -p "$pid" 2>/dev/null | tr -d ' ')" = "$RUSER" ] || continue
  name=$(tr '\0' ' ' < "/proc/$pid/cmdline" 2>/dev/null | grep -oE -- '-name prace-sr-(login|client) ' | cut -d' ' -f2)
  [ -n "$name" ] || continue
  kill "$pid"; for _ in $(seq 30); do kill -0 "$pid" 2>/dev/null || break; sleep 1; done
  kill -0 "$pid" 2>/dev/null && kill -9 "$pid"
  echo "   $name (QEMU $pid) stopped"
done
rm -rf "$SDIR" /root/prace-sr-upload /root/prace-sr-stage.*
bad=""
[ ! -e "$SDIR" ] || bad="$bad $SDIR"
pgrep -u "$RUSER" -f -- '-name prace-sr-' >/dev/null && bad="$bad qemu"
for p in $TCP; do [ -z "$(ss -Hltn "sport = :$p")" ] || bad="$bad tcp/$p"; done
for p in $UDP; do [ -z "$(ss -Hlun "sport = :$p")" ] || bad="$bad udp/$p"; done
[ -z "$bad" ] || { echo "   STILL PRESENT:$bad"; exit 1; }
echo "   gone: $SDIR (disks, seeds, consoles), prace-sr-* QEMU processes; nothing bound to tcp ${TCP// /,} or udp ${UDP// /,}"
REMOTE
  if [ -d "$KEYDIR" ]; then
    ssh -o ControlPath="$KEYDIR/jump" -O exit "$LOGIN" >/dev/null 2>&1 || true
    rm -rf "$KEYDIR"
  fi
  echo "   $KEYDIR removed (throwaway key, known_hosts, ssh config)"
}

cmd_status() {
  local out vm n_up=0 n_any=0 alive
  echo "== $(date +%T) status"
  out=$(L SDIR="$SDIR" RUSER="$RUSER" VMS="$(q "$VMS")" TCP="$(q "${PORT[sr-login]} ${PORT[sr-client]}")" \
      UDP="$(q "${LINK_PORT[sr-login]} ${LINK_PORT[sr-client]}")" bash -s <<'REMOTE'
for vm in $VMS; do
  st=stopped
  pid=$(cat "$SDIR/$vm.pid" 2>/dev/null)
  if [ -n "$pid" ] && [ "$(ps -o user= -p "$pid" 2>/dev/null | tr -d ' ')" = "$RUSER" ] \
     && tr '\0' ' ' < "/proc/$pid/cmdline" 2>/dev/null | grep -q -- "-name prace-$vm "; then st="running(QEMU $pid)"
  elif pgrep -u "$RUSER" -f -- "-name prace-$vm " >/dev/null; then st="running(no pidfile)"; fi
  echo "vm $vm $st"
done
echo "dir $([ -d "$SDIR" ] && du -sh "$SDIR" | cut -f1 || echo absent)"
echo "tcp $(for p in $TCP; do ss -Hltn "sport = :$p"; done | awk '{print $4}' | sort | paste -sd' ')"
echo "udp $(for p in $UDP; do ss -Hlun "sport = :$p"; done | awk '{print $4}' | sort | paste -sd' ')"
REMOTE
  ) || { echo "   login node not reachable"; exit 1; }
  echo "   state directory $SDIR: $(sed -n 's/^dir //p' <<<"$out")"
  echo "   listening on the login node: tcp $(sed -n 's/^tcp //p' <<<"$out" | sed 's/^$/none/'); udp $(sed -n 's/^udp //p' <<<"$out" | sed 's/^$/none/')"
  echo "   key directory $KEYDIR: $([ -f "$KEYDIR/id" ] && echo present || echo absent)"
  [ "$(sed -n 's/^dir //p' <<<"$out")" = absent ] || n_any=1
  [ -d "$KEYDIR" ] && n_any=1
  for vm in $VMS; do
    alive=$(sed -n "s/^vm $vm //p" <<<"$out")
    if [ "$alive" = stopped ]; then echo "   $vm: stopped"; continue; fi
    n_any=1
    if [ -f "$KEYDIR/id" ] && s=$(V "$vm" 'echo "$(hostname) up $(uptime -p | sed "s/^up //"); /home on $(findmnt -no SOURCE,FSTYPE --target /home | xargs)$(vgs --noheadings --units g -o vg_name,vg_size,vg_free,lv_count 2>/dev/null | awk "{printf \"; VG %s %s, free %s, %s LV\", \$1, \$2, \$3, \$4}")"' 2>/dev/null); then
      echo "   $vm: $alive; ssh ok (pinned host key): $s"; n_up=$((n_up + 1))
    else
      echo "   $vm: $alive; ssh NOT answering"
    fi
  done
  if [ "$n_up" = 2 ]; then echo "RESULT: UP"; return 0; fi
  if [ "$n_any" = 0 ]; then echo "RESULT: DOWN"; return 3; fi
  echo "RESULT: PARTIAL (run '$0 down', then '$0 up')"; return 1
}

cmd_wait() {   # cmd_wait <vm> <timeout seconds>
  local vm=$1 timeout=$2 t0 alive st boot
  [ -f "$KEYDIR/id" ] || { echo "no throwaway key in $KEYDIR (run '$0 up')"; exit 3; }
  echo "== $(date +%T) wait for $vm (up to ${timeout} s): ssh with the pinned host key"
  t0=$(date +%s)
  while :; do
    alive=$(L "pid=\$(cat $SDIR/$vm.pid 2>/dev/null) && [ \"\$(ps -o user= -p \"\$pid\" | tr -d ' ')\" = $RUSER ] && tr '\\0' ' ' < /proc/\$pid/cmdline | grep -q -- '-name prace-$vm ' && echo RUNNING || echo STOPPED") \
      || fail "login node not reachable"
    [ "$alive" = RUNNING ] || fail "$vm is not running (powered off or deleted); '$0 down' then '$0 up' recreates it"
    V "$vm" true 2>/dev/null && break
    [ $(( $(date +%s) - t0 )) -lt "$timeout" ] || fail "$vm did not answer ssh within ${timeout} s"
    sleep 5
  done
  st=$(V "$vm" "timeout $(( timeout > 60 ? timeout : 60 )) systemctl is-system-running --wait 2>/dev/null" || true)
  boot=$(V "$vm" 'echo "boot $(cut -c1-8 /proc/sys/kernel/random/boot_id), up $(uptime -p | sed "s/^up //")"') || fail "$vm stopped answering"
  echo "   $vm: ssh ok after $(( $(date +%s) - t0 )) s; $boot; systemd: ${st:-unknown}"
  if [ "$st" != running ]; then
    V "$vm" 'systemctl --failed --no-legend --plain' 2>/dev/null | sed 's/^/   failed unit: /' || true
    echo "RESULT: $vm answers but systemd is '${st:-unknown}'"; return 1
  fi
  echo "RESULT: $vm ready"
}

usage() { echo "usage: $0 up [--hold-on-failure] | status | wait sr-login|sr-client [--timeout SECONDS] | down" >&2; exit 2; }

main() {
  local cmd=${1:-} wait_vm="" timeout=600
  shift || true
  case $cmd in
    up) while [ $# -gt 0 ]; do case $1 in --hold-on-failure) HOLD=1; shift ;; *) usage ;; esac; done ;;
    status|down) [ $# -eq 0 ] || usage ;;
    wait)
      wait_vm=${1:-}; shift || true
      case $wait_vm in sr-login|sr-client) ;; *) usage ;; esac
      while [ $# -gt 0 ]; do
        case $1 in --timeout) [[ ${2:-} =~ ^[1-9][0-9]*$ ]] || usage; timeout=$2; shift 2 ;; *) usage ;; esac
      done ;;
    *) usage ;;
  esac
  mux_open
  case $cmd in
    up) cmd_up ;;
    down) trap mux_close EXIT; do_down ;;
    status) trap mux_close EXIT; cmd_status ;;
    wait) trap mux_close EXIT; cmd_wait "$wait_vm" "$timeout" ;;
  esac
}

